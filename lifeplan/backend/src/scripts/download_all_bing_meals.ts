async function getBingFoodThumb(query: string): Promise<string | null> {
  const url = `https://www.bing.com/images/search?q=${encodeURIComponent(query + ' เมนู อาหาร')}&first=1&scenario=ImageBasicHover`;
  try {
    const res = await fetch(url, {
      headers: {
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36',
        'Accept-Language': 'th,en-US;q=0.9,en;q=0.8',
      },
    });
    if (!res.ok) return null;
    const html = await res.text();
    const thumbs = [...html.matchAll(/(https:\/\/tse\d\.mm\.bing\.net\/th\/id\/OIP\.[^"&?]+)/g)].map((m) => m[1]);
    if (thumbs.length > 0) {
      return thumbs[0];
    }
  } catch {
    return null;
  }
  return null;
}

async function downloadImage(url: string, destPath: string): Promise<boolean> {
  try {
    const res = await fetch(url);
    if (!res.ok) return false;
    const buffer = Buffer.from(await res.arrayBuffer());
    if (buffer.length < 3000) return false;
    fs.writeFileSync(destPath, buffer);
    return true;
  } catch {
    return false;
  }
}

async function main() {
  const publicDir = path.resolve(process.cwd(), '../frontend/public/meals');
  const distDir = path.resolve(process.cwd(), '../frontend/dist/meals');

  console.log(`Starting Bing Thai Food Image Downloader for ${MEALS.length} meals...`);
  let successCount = 0;

  for (const m of MEALS) {
    const thumbUrl = await getBingFoodThumb(m.query);
    if (thumbUrl) {
      const targetPublic = path.join(publicDir, `meal_${m.id}.jpg`);
      const targetDist = path.join(distDir, `meal_${m.id}.jpg`);

      const ok = await downloadImage(thumbUrl, targetPublic);
      if (ok) {
        fs.copyFileSync(targetPublic, targetDist);
        successCount++;
        console.log(`[OK] Meal ${m.id}: ${m.name_th} (${thumbUrl.slice(0, 50)}...)`);
      } else {
        console.error(`[FAIL DOWNLOAD] Meal ${m.id}: ${m.name_th}`);
      }
    } else {
      console.error(`[NOT FOUND] Meal ${m.id}: ${m.name_th}`);
    }
    // Small delay between requests to be polite
    await new Promise((r) => setTimeout(r, 200));
  }

  console.log(`\nFinished! Successfully downloaded ${successCount} / ${MEALS.length} authentic food images.`);
}

main().catch(console.error);
